        \\
    , .{ in.version, in.grammarName, in.h.language, in.h.id, in.h.id });
    return out.written();
}

/// `vscode/package.json`.
pub fn packageJson(allocator: Allocator, in: Input) Error![]const u8 {
    const h = in.h;
    var out: Writer.Allocating = .init(allocator);
    const w = &out.writer;
    try w.writeAll("{\n  \"name\": ");
    try json.string(w, try std.mem.concat(allocator, u8, &.{ "vscode-", h.id }));
    try w.writeAll(",\n  \"displayName\": ");
    try json.string(w, h.language);
    try w.writeAll(",\n  \"description\": ");
    try json.string(w, try allocator.print("{s}: highlighting and its language server. Generated by nexus v{s} from {s}.", .{ h.language, in.version, in.grammarName }));
    try w.writeAll(",\n  \"version\": \"0.1.0\",\n  \"publisher\": ");
    try json.string(w, h.id);
    try w.print(",\n  \"engines\": {{\"vscode\": \"{s}\"}},\n  \"categories\": [\"Programming Languages\"],\n  \"main\": \"./extension.js\",\n  \"activationEvents\": [", .{vscode_engine});
    try json.string(w, try std.mem.concat(allocator, u8, &.{ "onLanguage:", h.id }));
    try w.print("],\n  \"dependencies\": {{\"vscode-languageclient\": \"{s}\"}},\n  \"contributes\": {{\n    \"languages\": [{{\n      \"id\": ", .{client_version});
    try json.string(w, h.id);
    try w.writeAll(",\n      \"aliases\": [");
    try json.string(w, h.language);
    try w.writeAll("],\n      \"extensions\": [");
    for (h.extensions, 0..) |ext, i| {
        if (i > 0) try w.writeAll(", ");
        try json.string(w, ext);
    }
    try w.writeAll("],\n      \"configuration\": \"./language-configuration.json\"\n    }],\n    \"grammars\": [{\n      \"language\": ");
    try json.string(w, h.id);
    try w.writeAll(",\n      \"scopeName\": ");
    try json.string(w, h.scopeName);
    try w.writeAll(",\n      \"path\": ");
    try json.string(w, try allocator.print("./syntaxes/{s}.tmLanguage.json", .{h.id}));
    try w.writeAll("\n    }],\n    \"configuration\": {\n      \"title\": ");
    try json.string(w, h.language);
    try w.writeAll(",\n      \"properties\": {\n        ");
    try json.string(w, try std.mem.concat(allocator, u8, &.{ h.id, ".server.path" }));
    try w.writeAll(": {\n          \"type\": \"string\",\n          \"default\": \"\",\n          \"markdownDescription\": ");
    try json.string(w, try allocator.print("The language server: a path, or a name on `PATH`. Empty: the extension's own `bin/{s}-lsp`, else `{s}-lsp` on `PATH`.", .{ h.id, h.id }));
    try w.writeAll("\n        },\n        ");
    try json.string(w, try std.mem.concat(allocator, u8, &.{ h.id, ".server.root" }));
    try w.writeAll(": {\n          \"type\": \"string\",\n          \"default\": \"\",\n          \"markdownDescription\": \"The file the program starts from, which the server analyzes. Empty: the file opened or saved.\"\n        }\n      }\n    },\n    \"semanticTokenTypes\": [");
    var n: usize = 0;
    for (std.enums.values(Scope)) |scope| {
        const name = try tokenType(allocator, scope);
        if (isStandard(name)) continue;
        try w.writeAll(if (n > 0) ",\n      " else "\n      ");
        n += 1;
        try w.writeAll("{\"id\": ");
        try json.string(w, name);
        try w.writeAll(", \"description\": ");
        try json.string(w, try allocator.print("@highlight {s}", .{scope.names().name}));
        try w.writeAll("}");
    }
    try w.writeAll("\n    ],\n    \"semanticTokenScopes\": [{\n      \"language\": ");
    try json.string(w, h.id);
    try w.writeAll(",\n      \"scopes\": {");
    for (std.enums.values(Scope), 0..) |scope, i| {
        try w.writeAll(if (i > 0) ",\n        " else "\n        ");
        try json.string(w, try tokenType(allocator, scope));
        try w.writeAll(": [");
        try json.string(w, try std.mem.concat(allocator, u8, &.{ scope.names().textmate, ".", h.id }));
        try w.writeAll("]");
    }
    try w.writeAll("\n      }\n    }]\n  }\n}\n");
    return out.written();
}

fn isStandard(name: []const u8) bool {
    for (standard_types) |s| if (std.mem.eql(u8, s, name)) return true;
    return false;
}

/// `vscode/extension.js`: the client, which starts the server for the
/// language's files.
pub fn extensionJs(allocator: Allocator, in: Input) Error![]const u8 {
    const h = in.h;
    var out: Writer.Allocating = .init(allocator);
    const w = &out.writer;
    var id: Writer.Allocating = .init(allocator);
    try json.string(&id.writer, h.id);
    var language: Writer.Allocating = .init(allocator);
    try json.string(&language.writer, h.language);
    try w.print(
        \\// Generated by nexus v{s} from {s}; do not edit.
        \\// The client: it starts the language server (the setting
        \\// `{s}.server.path`, else this extension's bin/{s}-lsp, else
        \\// `{s}-lsp` on PATH) and connects it to the language's files. The
        \\// TextMate grammar colours them whether or not the server starts.
        \\const fs = require("fs");
        \\const path = require("path");
        \\const vscode = require("vscode");
        \\const {{ LanguageClient }} = require("vscode-languageclient/node");
        \\
        \\const id = {s};
        \\const language = {s};
        \\
        \\/** @type {{LanguageClient | undefined}} */
        \\let client;
        \\
        \\/** @param {{vscode.ExtensionContext}} context */
        \\function serverCommand(context) {{
        \\  const set = vscode.workspace.getConfiguration(id).get("server.path");
        \\  if (set) return set;
        \\  const bundled = context.asAbsolutePath(path.join("bin", id + "-lsp" + (process.platform === "win32" ? ".exe" : "")));
        \\  return fs.existsSync(bundled) ? bundled : id + "-lsp";
        \\}}
        \\
        \\/** @param {{vscode.ExtensionContext}} context */
        \\async function start(context) {{
        \\  const command = serverCommand(context);
        \\  const server = {{ command, args: [] }};
        \\  client = new LanguageClient(id, language, {{ run: server, debug: server }}, {{
        \\    documentSelector: [{{ language: id }}],
        \\    initializationOptions: {{ root: vscode.workspace.getConfiguration(id).get("server.root") || "" }},
        \\  }});
        \\  try {{
        \\    await client.start();
        \\  }} catch (err) {{
        \\    client = undefined;
        \\    vscode.window.showWarningMessage(
        \\      `${{language}}: the language server did not start (\`${{command}}\`: ${{err.message}}). ` +
        \\        `Set ${{id}}.server.path to it; highlighting works without it.`,
        \\    );
        \\  }}
        \\}}
        \\
        \\async function stop() {{
        \\  const running = client;
        \\  client = undefined;
        \\  if (running) await running.stop();
        \\}}
        \\
        \\/** @param {{vscode.ExtensionContext}} context */
        \\async function activate(context) {{
        \\  context.subscriptions.push(
        \\    vscode.workspace.onDidChangeConfiguration(async (e) => {{
        \\      if (!e.affectsConfiguration(id + ".server")) return;
        \\      await stop();
        \\      await start(context);
        \\    }}),
        \\  );
        \\  await start(context);
        \\}}
        \\
        \\function deactivate() {{
        \\  return stop();
        \\}}
        \\
        \\module.exports = {{ activate, deactivate }};
        \\
    , .{ in.version, in.grammarName, h.id, h.id, h.id, id.written(), language.written() });
    return out.written();
}

/// A file of the server copied from the language: its path under
/// `server/src` and its text.
pub const Copied = struct { path: []const u8, text: []const u8 };

/// The files of the server's src/ that are its own: no lang file may take
/// one of their names.
pub const server_files = [_][]const u8{ "main.zig", "lsp.zig", "parser.zig", "language.zig", "hooks.zig" };

/// The lang module at `module` (written `name`.zig in the server, as the
/// parser imports it) and every file it imports by relative path, each
/// once, at the same paths relative to it. `bad` names a file that cannot
/// be read or lies outside the lang module's directory; `clash`, one of
/// `server_files` that the lang module would bring.
pub fn langFiles(allocator: Allocator, io: std.Io, module: []const u8, name: []const u8) Allocator.Error!union(enum) { files: []const Copied, bad: []const u8, clash: []const u8 } {
    const dir = std.fs.path.dirname(module) orelse "";
    var files: std.ArrayList(Copied) = .empty;
    var sources: std.ArrayList([]const u8) = .empty;
    const own = try std.mem.concat(allocator, u8, &.{ name, ".zig" });
    if (isServerFile(own)) return .{ .clash = own };
    try files.append(allocator, .{ .path = own, .text = "" });
    try sources.append(allocator, std.fs.path.basename(module));
    var i: usize = 0;
    while (i < files.items.len) : (i += 1) {
        const full = try std.fs.path.join(allocator, &.{ dir, sources.items[i] });
        const text = std.Io.Dir.cwd().readFileAlloc(io, full, allocator, .limited(16 << 20)) catch return .{ .bad = full };
        files.items[i].text = text;
        var rest = text;
        const needle = "@import(\"";
        while (std.mem.find(u8, rest, needle)) |at| {
            rest = rest[at + needle.len ..];
            const close = std.mem.findScalar(u8, rest, '"') orelse break;
            const imported = rest[0..close];
            if (!std.mem.endsWith(u8, imported, ".zig")) continue;
            const rel = try std.fs.path.resolveAllocPosix(allocator, &.{ std.fs.path.dirnamePosix(sources.items[i]) orelse ".", imported });
            if (std.mem.startsWith(u8, rel, "..")) return .{ .bad = try std.fs.path.join(allocator, &.{ dir, rel }) };
            // parser.zig is the server's own.
            if (std.mem.eql(u8, rel, "parser.zig")) continue;
            if (isServerFile(rel)) return .{ .clash = rel };
            const seen = for (sources.items) |f| {
                if (std.mem.eql(u8, f, rel)) break true;
            } else false;
            if (seen) continue;
            try files.append(allocator, .{ .path = rel, .text = "" });
            try sources.append(allocator, rel);
        }
    }
    return .{ .files = files.items };
}

fn isServerFile(path: []const u8) bool {
    for (server_files) |f| {
        if (std.mem.eql(u8, path, f)) return true;
    }
    return false;
}
