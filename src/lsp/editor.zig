    var out: Writer.Allocating = .init(allocator);
    const w = &out.writer;
    try w.print(
        \\//! Generated by nexus v{s} from {s} — do not edit
        \\//! The {s} language server: `zig build` installs zig-out/bin/{s}-lsp;
        \\//! `zig build --prefix ../vscode` puts it inside the extension.
        \\
        \\const std = @import("std");
        \\
        \\pub fn build(b: *std.Build) void {{
        \\    const target = b.standardTargetOptions(.{{}});
        \\    const optimize = b.standardOptimizeOption(.{{}});
        \\    const exe = b.addExecutable(.{{
        \\        .name = "{s}-lsp",
        \\        .root_module = b.createModule(.{{
        \\            .root_source_file = b.path("src/main.zig"),
        \\            .target = target,
        \\            .optimize = optimize,
        \\        }}),
        \\    }});
        \\    b.installArtifact(exe);
        \\    const tests = b.addRunArtifact(b.addTest(.{{ .root_module = exe.root_module }}));
        \\    b.step("test", "Run the server's tests").dependOn(&tests.step);
