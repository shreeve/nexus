//! editor.zig: the files of `nexus --editor`, a VS Code extension and a
//! language server for the language of one grammar file (docs/LSP.md).
//!
//!   vscode/                  the extension: package.json, extension.js, the
//!                            TextMate grammar, language-configuration.json
//!   vim/, highlightjs/       the other editor files of `@highlight`
//!   server/                  the language server: build.zig, and in src/
//!                            main.zig, lsp.zig (server_template.zig),
//!                            parser.zig, language.zig, the lang module and
//!                            the files it imports, and hooks.zig
//!
//! Every file is written again on every run but `server/src/hooks.zig`,
//! the language's own functions, which is written once.

const std = @import("std");
const Allocator = std.mem.Allocator;
const Writer = std.Io.Writer;
const json = @import("../json.zig");
const grammar = @import("../grammar.zig");
const Grammar = grammar.Grammar;
const highlight = @import("../highlight/highlight.zig");
const Highlight = highlight.Highlight;
const Scope = highlight.Scope;

pub const server_template = @embedFile("server_template.zig");

/// The version of vscode-languageclient the extension depends on, and the
/// VS Code it needs.
const client_version = "9.0.1";
const vscode_engine = "^1.82.0";

/// The scopes the semantic token types are named after; LSP's own types
/// are not declared again.
const standard_types = [_][]const u8{ "keyword", "string", "comment", "operator", "type", "function", "label" };

pub const Error = Allocator.Error || Writer.Error;

pub const Input = struct {
    h: *const Highlight,
    g: *const Grammar,
    spec: *const grammar.LexerSpec,
    keywordGroups: []const grammar.KeywordGroup,
    grammarName: []const u8,
    version: []const u8,
};

/// The semantic token type of a scope: its name in camel case
/// (`keyword.control`: `keywordControl`).
pub fn tokenType(allocator: Allocator, scope: Scope) Allocator.Error![]const u8 {
    const name = scope.names().name;
    var out: std.ArrayList(u8) = .empty;
    var upper = false;
    for (name) |c| {
        if (c == '.') {
            upper = true;
            continue;
        }
        try out.append(allocator, if (upper) std.ascii.toUpper(c) else c);
        upper = false;
    }
    return out.toOwnedSlice(allocator);
}

fn header(w: *Writer, in: Input, comptime what: []const u8) Writer.Error!void {
    try w.print("//! Generated by nexus v{s} from {s} — do not edit\n//! " ++ what ++ "\n\n", .{ in.version, in.grammarName });
}

/// `server/src/language.zig`: the language's names, each token's scope and
/// the words `@highlight` colours, the words completion offers, and the
/// characters of words.
pub fn languageZig(allocator: Allocator, in: Input) Error![]const u8 {
    var out: Writer.Allocating = .init(allocator);
    const w = &out.writer;
    try header(w, in, "The language's table for lsp.zig.");
    try w.writeAll("const std = @import(\"std\");\nconst lsp = @import(\"lsp.zig\");\nconst parser = @import(\"parser.zig\");\n\n");
    try w.print("pub const name = \"{f}\";\npub const id = \"{f}\";\n", .{ std.zig.fmtString(in.h.language), std.zig.fmtString(in.h.id) });

    // Token entries: a scope per token category.
    try w.writeAll("\n/// The scope of a token by its category: the token entries of `@highlight`.\npub fn tokenScope(cat: parser.TokenCat) ?lsp.Scope {\n");
    var cats: std.ArrayList(struct { cat: []const u8, scope: Scope }) = .empty;
    for (in.h.entries) |e| {
        if (!plain(e)) continue;
        for (e.tokens) |t| for (in.spec.tokens.items) |cat| {
            if (!std.ascii.eqlIgnoreCase(cat, t)) continue;
            const seen = for (cats.items) |c| {
                if (std.mem.eql(u8, c.cat, cat)) break true;
            } else false;
            if (!seen) try cats.append(allocator, .{ .cat = cat, .scope = e.scope });
        };
    }
    if (cats.items.len == 0) {
        try w.writeAll("    _ = cat;\n    return null;\n}\n");
    } else {
        try w.writeAll("    return switch (cat) {\n");
        for (cats.items) |c| try w.print("        .{f} => .{s},\n", .{ std.zig.fmtIdPU(c.cat), @tagName(c.scope) });
        try w.writeAll("        else => null,\n    };\n}\n");
    }

    // Literal and @keywords entries: a scope per spelling.
    const Word = struct { text: []const u8, scope: Scope };
    var exact: std.ArrayList(Word) = .empty;
    var folded: std.ArrayList(Word) = .empty;
    for (in.h.entries) |e| {
        if (!plain(e)) continue;
        for (e.literals) |l| try addWord(allocator, &exact, l, e.scope);
        for (e.groups) |name| for (in.keywordGroups) |group| {
            if (!std.mem.eql(u8, group.name, name)) continue;
            for (group.entries) |ge| for (ge.min..ge.word.len + 1) |n| {
                if (n == 0) continue;
                if (group.caseless) {
                    try addWord(allocator, &folded, try std.ascii.allocLowerString(allocator, ge.word[0..n]), e.scope);
                } else try addWord(allocator, &exact, ge.word[0..n], e.scope);
            };
        };
    }
    var longest: usize = 0;
    for (folded.items) |f| longest = @max(longest, f.text.len);
    try w.writeAll("\n/// The scope of a token by its text: the literal and `@keywords` entries of\n/// `@highlight`.\npub fn wordScope(text: []const u8) ?lsp.Scope {\n");
    if (exact.items.len == 0 and folded.items.len == 0) try w.writeAll("    _ = text;\n");
    if (exact.items.len > 0) try w.writeAll("    if (exact.get(text)) |scope| return scope;\n");
    if (folded.items.len > 0) try w.print(
        \\    if (text.len > {d}) return null;
        \\    var buf: [{d}]u8 = undefined;
        \\    return caseless.get(std.ascii.lowerString(&buf, text));
        \\
    , .{ longest, longest }) else try w.writeAll("    return null;\n");
    try w.writeAll("}\n");
    for ([_]struct { []const u8, []const Word }{ .{ "exact", exact.items }, .{ "caseless", folded.items } }) |pair| {
        if (pair[1].len == 0) continue;
        try w.print("\nconst {s} = std.StaticStringMap(lsp.Scope).initComptime(.{{\n", .{pair[0]});
        for (pair[1]) |word| try w.print("    .{{ \"{f}\", .{s} }},\n", .{ std.zig.fmtString(word.text), @tagName(word.scope) });
        try w.writeAll("});\n");
    }

    // The words a terminal stands for, which completion offers.
    try w.writeAll("\n/// The words completion offers where the grammar takes them: each literal\n/// terminal, token whose one rule is a literal, and `@keywords` terminal\n/// that is a word.\npub const words: []const []const u8 = &.{");
    var words: std.ArrayList([]const u8) = .empty;
    for (in.g.symbols.items) |sym| {
        if (sym.kind != .terminal or sym.name.len < 3 or sym.name[0] != '"') continue;
        const text = sym.name[1 .. sym.name.len - 1];
        if (isWord(in.h, text)) try words.append(allocator, text);
    }
    for (in.g.tokenMap) |b| {
        if (in.g.symbols.items[b.sym].name[0] == '"') continue;
        var only: ?[]const u8 = null;
        var count: usize = 0;
        for (in.spec.rules.items) |r| if (!r.isSkip and std.mem.eql(u8, r.token, b.cat)) {
            only = r.literal;
            count += 1;
        };
        if (count == 1) if (only) |text| if (isWord(in.h, text)) try words.append(allocator, text);
    }
    for (in.g.keywordGroups) |group| for (0..group.terminals.len) |i| {
        var word: ?[]const u8 = null;
        var count: usize = 0;
        for (group.entries) |ge| if (ge.terminal == i and !ge.alias) {
            word = ge.word;
            count += 1;
        };
        if (count == 1) try words.append(allocator, word.?);
    };
    std.mem.sort([]const u8, words.items, {}, struct {
        fn lt(_: void, x: []const u8, y: []const u8) bool {
            return std.mem.order(u8, x, y) == .lt;
        }
    }.lt);
    for (words.items, 0..) |word, i| {
        if (i > 0 and std.mem.eql(u8, words.items[i - 1], word)) continue;
        try w.print("\n    \"{f}\",", .{std.zig.fmtString(word)});
    }
    try w.writeAll(if (words.items.len > 0) "\n};\n" else "};\n");

    // word-chars
    try w.writeAll("\n/// Whether `c` is a character of words (`@highlight` word-chars).\npub fn isWord(c: u8) bool {\n    return switch (c) {\n");
    var c: usize = 0;
    var any = false;
    while (c < 256) {
        if (!in.h.wordChars.has(@intCast(c))) {
            c += 1;
            continue;
        }
        var end = c;
        while (end + 1 < 256 and in.h.wordChars.has(@intCast(end + 1))) end += 1;
        try w.writeAll(if (any) ", " else "        ");
        any = true;
        if (end == c) try w.print("{d}", .{c}) else try w.print("{d}...{d}", .{ c, end });
        c = end + 1;
    }
    if (any) try w.writeAll(" => true,\n");
    try w.writeAll("        else => false,\n    };\n}\n");
    return out.written();
}

/// An entry the server applies to whole tokens: no pattern, no context,
/// not within a token.
fn plain(e: highlight.Entry) bool {
    return e.pattern == null and e.contexts.len == 0 and !e.lineStart and !e.lineEnd and e.within == null;
}

fn addWord(allocator: Allocator, list: anytype, text: []const u8, scope: Scope) Allocator.Error!void {
    for (list.items) |w| if (std.mem.eql(u8, w.text, text)) return;
    try list.append(allocator, .{ .text = text, .scope = scope });
}

/// Whether every byte of `text` is a word character.
fn isWord(h: *const Highlight, text: []const u8) bool {
    if (text.len == 0) return false;
    for (text) |c| if (!h.wordChars.has(c)) return false;
    return true;
}

/// `server/src/hooks.zig`, written once: every function `lsp.todo`.
pub fn hooksZig(allocator: Allocator, in: Input) Error![]const u8 {
    var out: Writer.Allocating = .init(allocator);
    const w = &out.writer;
    try w.print(
        \\//! hooks.zig: what the {s} language server knows beyond the grammar.
        \\//!
        \\//! `nexus --editor` wrote this file once and never writes it again; it
        \\//! is the language's to fill in (docs/LSP.md). lsp.zig calls only the
        \\//! functions written here: each `= lsp.todo` leaves its features off.
        \\//! Replace one with a function of the signature above it to turn them on.
        \\
        \\const std = @import("std");
        \\const lsp = @import("lsp.zig");
        \\const parser = @import("parser.zig");
        \\
        \\
    , .{in.h.language});
    try w.writeAll(hooks_body);
    return out.written();
}

