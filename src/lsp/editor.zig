fn isStandard(name: []const u8) bool {
    for (standard_types) |s| if (std.mem.eql(u8, s, name)) return true;
    return false;
}

/// The standard type a theme colours a scope's token type by when it
/// does not know the type itself; punctuation and invalid have none.
fn superType(scope: Scope) ?[]const u8 {
    return switch (scope) {
        .keyword_control, .keyword_operator, .storage_modifier => "keyword",
        .constant, .constant_symbol => "enumMember",
        .constant_numeric => "number",
        .string_escape => "string",
        .function_builtin => "function",
        .variable_parameter => "parameter",
        .variable_special => "variable",
        .keyword, .string, .comment, .operator, .type, .function, .label, .punctuation, .invalid => null,
    };
}

